export interface ApiEndpoint {
  id: string;
  provider: string;
  /** Base URL for the provider. Omit for ClawAPIs (default). */
  baseUrl?: string;
  /** API path on the provider. Omit only for legacy ClawAPIs endpoints. */
  path?: string;
  name: string;
  description: string;
  category: 'solana' | 'social' | 'utility' | 'defi' | 'intelligence' | 'oracle' | 'scraping' | 'discovery' | 'infrastructure' | 'search' | 'media' | 'enrichment' | 'weather' | 'ai-ml' | 'security';
  costPerCall: number;
  latencyMs: number;
  inputSchema: Record<string, string>;
  outputFields: string[];
  rateLimit?: number;
  /** Override cache TTL in seconds. Omit to use global CACHE_TTL_SECONDS (300s default). */
  cacheTtl?: number;
  /** Fixed credit cost per invocation (value-based pricing). Omit to auto-tier from costPerCall. */
  creditCost?: number;
}

